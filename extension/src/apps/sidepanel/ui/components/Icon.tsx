type IconData = Parameters<typeof HugeiconsIcon>[0]["icon"];
type IconProps = Omit<ComponentProps<typeof HugeiconsIcon>, "icon">;

/**
 * Wraps a hugeicons icon data object into a React component.
 * To switch icon libraries, only this file needs to change.
 */
function icon(data: IconData) {
  const Comp = (props: IconProps) => <HugeiconsIcon icon={data} {...props} />;
  return Comp;
}

